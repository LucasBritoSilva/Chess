// DOM integration with the real WebAssembly engine; this is not a rendering test.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { JSDOM } from 'jsdom';

const html = await readFile(new URL('../web/index.html', import.meta.url), 'utf8');
const dom = new JSDOM(html, { url: 'http://localhost:8080/', pretendToBeVisual: true });
const { window } = dom;
globalThis.document = window.document;
globalThis.Option = window.Option;
// jsdom does not implement modal dialog focus/top-layer behavior.
window.HTMLDialogElement.prototype.showModal = function () { this.open = true; };
window.HTMLDialogElement.prototype.close = function () {
  this.open = false;
  this.dispatchEvent(new window.Event('close'));
};
await import('../web/js/app.js');
const $ = id => document.getElementById(id);
const square = name => document.querySelector(`[data-square="${name}"]`);
const click = id => $(id).click();
const move = (from, to) => { square(from).click(); square(to).click(); };
const restart = () => { click('new-game'); click('confirm-ok'); };
const playSequence = moves => { for (const m of moves) move(m.slice(0, 2), m.slice(2, 4)); };
const checkTitle = text => assert.equal($('status-title').textContent, text);

checkTitle('Brancas jogam.');
assert.equal(document.querySelectorAll('.square').length, 64);
assert.equal(document.querySelectorAll('.square svg').length, 32);
assert.equal($('board').getAttribute('aria-busy'), 'false');
assert.equal($('white-tag').hidden, false);
square('e2').click();
assert.equal(document.querySelectorAll('.legal').length, 2);
assert.equal(square('e2').getAttribute('aria-pressed'), 'true');
square('e5').click();
assert.match($('feedback').textContent, /inválido/);
assert.equal(document.querySelectorAll('#history li').length, 0);
square('e4').click();
checkTitle('Pretas jogam.');
assert.match(square('e4').getAttribute('aria-label'), /peão branco/);
assert.match($('history').textContent, /e4/);
assert.equal($('white-tag').hidden, true);
assert.equal($('black-tag').hidden, false);
click('new-game');
assert.equal($('confirm-dialog').open, true);
click('confirm-cancel');
checkTitle('Pretas jogam.');
restart();
assert.equal($('history').children.length, 0);
assert.equal(document.querySelectorAll('.square svg').length, 32);
click('flip-board');
assert.equal($('board').firstElementChild.dataset.square, 'h1');
square('e2').focus();
square('e2').dispatchEvent(new window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }));
assert.equal(document.activeElement.dataset.square, 'f2');
click('flip-board');
assert.equal($('board').firstElementChild.dataset.square, 'a8');
square('e2').click();
square('e2').dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
assert.equal(document.querySelectorAll('.selected').length, 0);

playSequence(['f2f3', 'e7e5', 'g2g4', 'd8h4']);
checkTitle('Pretas vencem!');
assert.match($('status-description').textContent, /xeque-mate/);
assert.match($('history').textContent, /Qh4#/);
assert.equal($('draw-agreement').disabled, true);
const endedHistory = $('history').textContent;
move('e2', 'e4');
assert.equal($('history').textContent, endedHistory);
restart();
playSequence(['e2e4', 'a7a6', 'e4e5', 'd7d5', 'e5d6']);
assert.match(square('d5').getAttribute('aria-label'), /vazia/);
assert.equal($('captured-white').querySelectorAll('svg').length, 1);
assert.match($('history').textContent, /exd6/);
restart();
playSequence(['g1f3', 'g8f6', 'e2e3', 'e7e6', 'f1e2', 'f8e7', 'e1g1']);
assert.match(square('f1').getAttribute('aria-label'), /torre branco/);
assert.match($('history').textContent, /O-O/);
restart();
playSequence(['a2a4', 'h7h5', 'a4a5', 'h5h4', 'a5a6', 'h4h3', 'a6b7', 'h3g2', 'b7a8']);
assert.equal($('promotion-dialog').open, true);
assert.equal($('promotion-options').children.length, 4);
click('cancel-promotion');
assert.match(square('b7').getAttribute('aria-label'), /peão branco/);
square('a8').click();
$('promotion-options').querySelector('[aria-label="Promover a cavalo"]').click();
assert.equal($('promotion-dialog').open, false);
assert.match(square('a8').getAttribute('aria-label'), /cavalo branco/);
assert.match($('history').textContent, /bxa8=N/);
restart();
playSequence(['g1f3', 'g8f6', 'f3g1', 'f6g8', 'g1f3', 'g8f6', 'f3g1']);
assert.equal($('claim-draw').hidden, false);
click('claim-draw');
assert.equal($('claim-dialog').open, true);
assert.match($('claim-move').textContent, /f6 → g8/);
click('claim-cancel');
move('f6', 'g8');
click('claim-draw');
assert.equal($('claim-move').value, 'current');
click('claim-ok');
checkTitle('Empate.');
assert.equal($('claim-draw').hidden, true);
restart();
click('draw-agreement');
click('confirm-cancel');
checkTitle('Brancas jogam.');
click('draw-agreement');
click('confirm-ok');
checkTitle('Empate.');
assert.match($('status-description').textContent, /concordaram/);
restart();
checkTitle('Brancas jogam.');
console.log('PASS: DOM + real WebAssembly: selection, illegal moves, history, mate, reset, keyboard, flip, castling, en passant, promotion, draw dialogs.');
window.close();
